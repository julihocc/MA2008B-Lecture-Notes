# ## Solved Problem 3: Performance Region Interpretation
# 
# **Problem Statement:**
# Given the design requirements:
# $$ \zeta \ge 0.5 \quad \text{and} \quad \omega_n \le 4 $$
# Describe and visually plot the admissible dominant-pole region in the s-plane.

# %%
print_section("Solved Problem 3: Performance Region Interpretation")

print("Requirement 1: Damping ratio zeta >= 0.5")
print("  This defines a sector in the left-half-plane bounded by angle theta = arccos(0.5) = 60 degrees")
print("  measured from the negative real axis (or +/- 120 deg from the positive real axis).")

print("\nRequirement 2: Natural Frequency omega_n <= 4")
print("  This explicitly defines a circular disk centered at the origin with radius = 4.")

print("\nThe intersecting region of these two constraints forms a 'cone' slice of the disk in the LHP.")

# Visualizing the Admissible Region
plt.figure(figsize=(8, 8))

# Draw the natural frequency limit circle (radius 4)
theta_circle = np.linspace(0, 2*np.pi, 200)
x_circle = 4 * np.cos(theta_circle)
y_circle = 4 * np.sin(theta_circle)
plt.plot(x_circle, y_circle, 'b--', label='omega_n = 4 boundary')

# Draw the damping ratio limit rays
# angle from negative real axis is 60 deg -> angle from pos real axis is 120 and 240 deg
r = np.array([0, 5])
theta_damp1 = np.radians(120)
theta_damp2 = np.radians(240)

plt.plot(r * np.cos(theta_damp1), r * np.sin(theta_damp1), 'g-', label='zeta = 0.5 boundary')
plt.plot(r * np.cos(theta_damp2), r * np.sin(theta_damp2), 'g-')

# Fill the valid admissible region polygon
# The region is defined by the sector between 120 and 240 degrees up to radius 4
theta_region = np.linspace(theta_damp1, theta_damp2, 100)
x_fill = np.concatenate(([0], 4 * np.cos(theta_region), [0]))
y_fill = np.concatenate(([0], 4 * np.sin(theta_region), [0]))
plt.fill(x_fill, y_fill, 'g', alpha=0.3, label='Admissible Region')

style_plot("Admissible Performance Region (zeta >= 0.5, omega_n <= 4)")
plt.legend()
plt.xlim([-5, 1])
plt.ylim([-5, 5])
plt.gca().set_aspect('equal', adjustable='box')
plt.show()
