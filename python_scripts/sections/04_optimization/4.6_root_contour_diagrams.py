# We look into parameter space design, local sensitivity analysis using derivatives, and identifying regions of admissible performance based on complex plane geometry.

# %%
import numpy as np
import sympy as sp
import matplotlib.pyplot as plt
from sympy import symbols, Eq, solve, diff, I

s, K, K1, K2 = symbols('s K K1 K2')

# Helper function to print results nicely
def print_section(title):
    print(f"\n{'='*50}")
    print(f"{title}")
    print(f"{'='*50}")

# Helper to standardize plots
def style_plot(title):
    plt.title(title)
    plt.xlabel('Real Axis')
    plt.ylabel('Imaginary Axis')
    plt.grid(True)
    plt.axvline(x=0, color='k', linestyle='--', alpha=0.5)
    plt.axhline(y=0, color='k', linestyle='--', alpha=0.5)

# %% [markdown]
# ---
# ## Solved Problem 1: Parameter Space Design
# 
# **Problem Statement:**
# For the characteristic equation:
# $$ \Delta(s,K_1,K_2)=s(s+1)(s+3) + K_1(s+K_2) = 0 $$
# Find $(K_1, K_2)$ necessary to set the dominant poles at $\zeta = 0.7$, $\omega_n = 2$.

# %%
print_section("Solved Problem 1: Parameter Space Design")

zeta = 0.7
omega_n = 2.0

# Calculate desired dominant pole s_d
s_d_val = -zeta * omega_n + 1j * omega_n * np.sqrt(1 - zeta**2)
print(f"Target specified Damping Ratio: {zeta}")
print(f"Target specified Natural Frequency: {omega_n}")
print(f"Target Dominant Pole (s_d): {s_d_val:.3f}")

# Characteristic Equation representation evaluated at s_d
# Delta(s_d) = s_d*(s_d+1)*(s_d+3) + K1*s_d + K1*K2 = 0
A = s_d_val * (s_d_val + 1) * (s_d_val + 3)
print(f"\nValue of A = s_d(s_d+1)(s_d+3): {A:.3f}")

# The equation becomes A + K1*s_d + K1*K2 = 0
# Break it into real and imaginary parts:
# Re(A) + K1*Re(s_d) + K1*K2 = 0
# Im(A) + K1*Im(s_d) = 0

# From imaginary part:
# K1 * Im(s_d) = -Im(A)
K1_req = -np.imag(A) / np.imag(s_d_val)

# From real part:
# K1 * K2 = -Re(A) - K1 * Re(s_d)
K2_req = (-np.real(A) - K1_req * np.real(s_d_val)) / K1_req

print(f"\nSolving the simultaneous real/imaginary equations yields:")
print(f"Required parameter K1: {K1_req:.3f}")
print(f"Required parameter K2: {K2_req:.3f}")

# Validation
Delta_verify = s**3 + 4*s**2 + 3*s + K1_req*s + K1_req*K2_req
roots_generated = solve(Eq(Delta_verify, 0), s)

print(f"\nVerification - Roots generated by (K1, K2):")
for r in roots_generated:
    eval_r = complex(r.evalf())
    print(f"s = {eval_r:.3f}")

