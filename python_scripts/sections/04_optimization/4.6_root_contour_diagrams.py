# ## Solved Problem 2: Sensitivity Analysis
# 
# **Problem Statement:**
# Analyze the local sensitivity of the closed-loop pole locations to a 10% variation in $K$ for:
# $$ \Delta(s,K)=s^2+2s+K=0 $$
# Given nominal gain $K_0=4$, which places nominal poles at $s_0 = -1 \pm j\sqrt{3}$.

# %%
print_section("Solved Problem 2: Parameter Sensitivity Analysis")

Delta = s**2 + 2*s + K
K0 = 4.0

# Nominal pole calculation
nominal_roots = solve(Eq(Delta.subs(K, K0), 0), s)
s0 = nominal_roots[0] # Select the upper pole: -1 + i*sqrt(3)
print(f"Nominal Characteristic Equation: {Delta}")
print(f"Nominal Pole s_0 at K=4: {s0.evalf():.3f}")

# Calculate local sensitivity (ds/dK) using implicit differentiation:
# ds_dK = - (dDelta/dK) / (dDelta/ds)
dDelta_dK = diff(Delta, K)  # = 1
dDelta_ds = diff(Delta, s)  # = 2s + 2

ds_dK = -dDelta_dK / dDelta_ds
print(f"\nLocal Sensitivity Equation ds/dK: {ds_dK}")

# Evaluate at nominal pole s0
sensitivity_at_s0 = ds_dK.subs(s, s0)
print(f"Sensitivity evaluated at s_0: {sensitivity_at_s0.evalf():.3f}")

# Compare linear estimation vs. true displacement for a 10% change in K
delta_K = K0 * 0.10  # 10% increase = +0.4
linear_delta_s = sensitivity_at_s0 * delta_K

print(f"\n10% increase in K (Delta K = {delta_K})")
print(f"Linear Prediction of pole shift (Delta s): {linear_delta_s.evalf():.3f}")

# Calculate precise new pole
new_roots = solve(Eq(Delta.subs(K, K0 + delta_K), 0), s)
exact_new_pole = new_roots[0]
exact_delta_s = exact_new_pole - s0

print(f"Exact newly computed pole at K=4.4: {exact_new_pole.evalf():.3f}")
print(f"Exact actual pole shift (Delta s): {exact_delta_s.evalf():.3f}")
print("Conclusion: The linear sensitivity prediction closely tightly matches the exact shift!")

