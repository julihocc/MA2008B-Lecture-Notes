import numpy as np
import sympy as sp
import matplotlib.pyplot as plt
import control as ctrl
from sympy import symbols, Eq, solve, diff

s, K = symbols('s K')

def print_section(title):
    print(f"\n{'='*50}")
    print(f"{title}")
    print(f"{'='*50}")

def style_plot(title):
    plt.title(title)
    plt.xlabel('Real Axis')
    plt.ylabel('Imaginary Axis')
    plt.grid(True)
    plt.axvline(x=0, color='k', linestyle='--', alpha=0.5)
    plt.axhline(y=0, color='k', linestyle='--', alpha=0.5)

# %% [markdown]
# ---
# ## Solved Problem 1: Apply All Rules
# 
# **Problem Statement:**
# Construct the root locus for
# $$ 1 + \frac{K}{(s+1)(s^2+2s+2)} = 0 $$
# using systematic rules.

# %%
print_section("Solved Problem 1: Apply All Rules")

# Define Plant F(s)
# Note: s^2 + 2s + 2 has roots at -1 +/- j
s_ctrl = ctrl.TransferFunction.s
F1 = 1 / ((s_ctrl + 1) * (s_ctrl**2 + 2*s_ctrl + 2))

poles = ctrl.poles(F1)
zeros = ctrl.zeros(F1)
n = len(poles)
m = len(zeros)

print(f"Open-loop Poles: {np.round(poles, 2)}")
print(f"Branches to infinity (n - m): {n - m}")

# Asymptotes
sigma_a = np.sum(poles) / n
angles_deg = [(2*k + 1)*180 / n for k in range(n)]

print(f"\nCentroid (sigma_a): {float(np.real(sigma_a)):.2f}")
print(f"Asymptote Angles: {angles_deg} degrees")

print("\nReal-Axis Segments (Odd Rule):")
print("  Between [-1, -infinity] -> 1 real pole to the right. (Locus exists)")

# Departure Angle Calculation for the complex pole p = -1 + j
p_test = -1 + 1j
# The angle from the other complex pole p_conj = -1 - j to p_test:
angle_from_conj = np.degrees(np.angle(p_test - (-1 - 1j)))
# The angle from the real pole p_real = -1 to p_test:
angle_from_real = np.degrees(np.angle(p_test - (-1)))

# Rule: theta_dep = 180 + sum(angle from zeros) - sum(angle from other poles)
theta_dep = 180 - (angle_from_conj + angle_from_real)
print(f"\nDeparture Angle from pole s_p = -1 + j:")
print(f"  Angle from (-1 - j): {angle_from_conj} deg")
print(f"  Angle from (-1): {angle_from_real} deg")
print(f"  Calculated Theta_dep: {theta_dep} degrees")

# Verify visually
plt.figure(figsize=(8, 8))
ctrl.root_locus(F1, plot=True, grid=False)
plt.plot(sigma_a, 0, 'rx', markersize=10, label=f'Centroid: {float(np.real(sigma_a)):.2f}')
style_plot("Root Locus: 1 + K/((s+1)(s^2+2s+2))")
plt.legend()
plt.xlim([-4, 2])
plt.ylim([-3, 3])
plt.show()

