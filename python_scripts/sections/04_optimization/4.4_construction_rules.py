# ## Solved Problem 3: Imaginary-Axis Crossing by Routh
# 
# **Problem Statement:**
# Determine the marginal stability crossing gain and frequency for:
# $$ \Delta(s,K) = s^3 + 3s^2 + 2s + K = 0 $$

# %%
print_section("Solved Problem 3: Imaginary-Axis Crossing by Routh")

print("Applying Routh-Hurwitz Array to s^3 + 3s^2 + 2s + K:")
print("s^3: 1        2")
print("s^2: 3        K")
print("s^1: (6-K)/3")
print("s^0: K")

# A crossing occurs when the first entry of the s^1 row is zero
K_crit = 6.0
print(f"\nEquation from s^1 row zeroes out at: K = {K_crit}")

# The crossover frequencies come from the auxiliary equation formed by the s^2 row
# 3s^2 + K = 0
aux_eq = Eq(3*s**2 + K_crit, 0)
crossing_points = solve(aux_eq, s)

print("Imaginary Axis Crossing Frequencies (s = ±jw):")
cp0 = complex(crossing_points[0].evalf())
cp1 = complex(crossing_points[1].evalf())
print(f"s = {cp0.real:.3f} + {cp0.imag:.3f}j")
print(f"s = {cp1.real:.3f} + {cp1.imag:.3f}j")

# Verify graphically
F3 = 1 / (s_ctrl**3 + 3*s_ctrl**2 + 2*s_ctrl)
plt.figure(figsize=(8, 8))
ctrl.root_locus(F3, plot=True, grid=False)
plt.plot([0, 0], [np.sqrt(2), -np.sqrt(2)], 'ro', markersize=8, label='Marginal Stability Crossings')
style_plot("Root locus showing Imaginary-Axis crossings")
plt.legend()
plt.xlim([-4, 2])
plt.ylim([-3, 3])
plt.show()
