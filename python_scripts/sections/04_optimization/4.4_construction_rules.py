# ## Solved Problem 2: Design Using Root Locus
# 
# **Problem Statement:**
# For the characteristic equation:
# $$ \Delta(s,K) = s(s+2) + K = 0 $$
# find the gain $K$ required to place the closed-loop poles exactly at $s = -1 \pm j$.

# %%
print_section("Solved Problem 2: Design Using Root Locus")

# Characteristic polynomial
Delta2 = s*(s + 2) + K

# Substitute the target root s = -1 + j into the characteristic equation
target_root = -1 + 1j
Delta2_subbed = (target_root)*(target_root + 2) + K

print(f"Substituting s = -1 + j into the characteristic equation:")
print(f"((-1 + j)(-1 + j + 2)) + K = 0")

# Expand the complex multiplication
val = (-1 + 1j) * (1 + 1j)
print(f"Calculated complex value: {val} + K = 0")

K_req = -np.real(val)
print(f"\nRequired Gain K: {K_req}")

# Validate
Delta_val = s**2 + 2*s + K_req
roots = solve(Eq(Delta_val, 0), s)
print(f"Roots generated by K = {K_req}: {roots}")

